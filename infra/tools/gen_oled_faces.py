"""Generate oled_faces.h (raw RGB565 pixels per emotion) for the oled-faces firmware patch.

  uv run infra/tools/gen_oled_faces.py <faces dir> <output header>

File name = emotion name (happy.png -> "happy"); preview.png is skipped.
Pixels are reduced to pure black/white with the panel's rule (see preview_faces.py):
composed over white, a pixel is lit (black) if its RGB565 blue is <= 16. No decoding
happens on the board, so it shows exactly what make preview-faces shows.
"""
import os
import sys

from PIL import Image

faces_dir, out_path = sys.argv[1:3]
names = sorted(f[:-4] for f in os.listdir(faces_dir) if f.endswith(".png") and f != "preview.png")

lines = ["// Generated by make build from infra/faces/*.png. Do not edit.",
         "#pragma once", "#include <cstdint>", "",
         "struct OledFace { const char* name; uint16_t w; uint16_t h; const uint8_t* rgb565; };", ""]
sizes = {}
for name in names:
    img = Image.open(os.path.join(faces_dir, f"{name}.png")).convert("RGBA")
    rgb = Image.alpha_composite(Image.new("RGBA", img.size, (255, 255, 255, 255)), img).convert("RGB")
    data = []
    for y in range(img.height):
        for x in range(img.width):
            lit = (rgb.getpixel((x, y))[2] >> 3) <= 16
            data += [0, 0] if lit else [255, 255]  # black / white, same in either byte order
    lines.append(f"static const uint8_t oled_face_{name}[] = {{{','.join(map(str, data))}}};")
    sizes[name] = img.size
lines += ["", "static const OledFace kOledFaces[] = {"]
lines += [f'    {{"{n}", {sizes[n][0]}, {sizes[n][1]}, oled_face_{n}}},' for n in names]
lines += ["    {nullptr, 0, 0, nullptr},", "};", ""]

open(out_path, "w").write("\n".join(lines))
print(f"{len(names)} faces -> {out_path}")
